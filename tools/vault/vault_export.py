"""Writes the runtime model JSONs (1.21.1 item models), the full static model and the Blockbench source from the spec + atlas."""
from __future__ import annotations
import base64, io, json, uuid
import vault_spec as S

TEXTURE = "cobbletowers:item/halloween/jack_o_lantern_vault/vault"
NS_UUID = uuid.UUID("5a1c0b7e-9d4e-4f5a-8a7b-0c1d2e3f4a5b")


def num(v):
    v = round(float(v), 4)
    return int(v) if v == int(v) else v


def uv_json(rect, size):
    x, y, w, h = rect
    k = 16.0 / size
    return [round(x * k, 5), round(y * k, 5), round((x + w) * k, 5), round((y + h) * k, 5)]


def element_json(model, idx, rects, size):
    e = model.els[idx]
    faces = {}
    for f in S.FACES:
        if f in e.skip:
            continue
        faces[f] = {"uv": uv_json(rects[(idx, f)], size), "texture": "#0"}
    d = {"name": e.name, "from": [num(v) for v in e.frm], "to": [num(v) for v in e.to]}
    if e.rot:
        axis, ang, org = e.rot
        d["rotation"] = {"angle": ang, "axis": axis, "origin": [num(v) for v in org]}
    d["faces"] = faces
    return d


def model_json(model, pieces, rects, size):
    idxs = [i for i, e in enumerate(model.els) if e.piece in pieces]
    return {
        "credit": "Jack-o'-Lantern Vault, generated by tools/vault (original work for CobbleTowers)",
        "texture_size": [size, size],
        "textures": {"0": TEXTURE, "particle": TEXTURE},
        "elements": [element_json(model, i, rects, size) for i in idxs],
    }


def write_models(model, rects, size, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    files = {}
    for p in S.PIECES:
        files[p] = model_json(model, (p,), rects, size)
    files["vault_full"] = model_json(model, ("body", "lid", "face_plate", "candy_fill"), rects, size)
    for name, js in files.items():
        (out_dir / f"{name}.json").write_text(json.dumps(js, indent=1) + "\n")
    return sorted(files)


# Blockbench ---------------------------------------------------------------------------------------------------------------------------
def _u(name):
    return str(uuid.uuid5(NS_UUID, name))


def bbmodel(model, rects, size, atlas_png_bytes, animations):
    elements, groups = [], {}
    for i, e in enumerate(model.els):
        faces = {}
        for f in S.FACES:
            if f in e.skip:
                faces[f] = {"uv": [0, 0, 0, 0], "texture": None}
                continue
            x, y, w, h = rects[(i, f)]
            faces[f] = {"uv": [x, y, x + w, y + h], "texture": 0}
        d = {"name": e.name, "box_uv": False, "rescale": False, "locked": False, "light_emission": 0, "render_order": "default",
             "allow_mirror_modeling": True, "from": list(e.frm), "to": list(e.to), "autouv": 0, "color": (i * 7) % 12, "origin": [8, 0, 8],
             "faces": faces, "type": "cube", "uuid": _u("el:" + e.piece + ":" + e.name + f":{i}")}
        if e.rot:
            axis, ang, org = e.rot
            d["origin"] = list(org)
            d["rotation"] = [ang if axis == "x" else 0, ang if axis == "y" else 0, ang if axis == "z" else 0]
        elements.append(d)
        groups.setdefault(e.piece, {}).setdefault(e.group or "misc", []).append(d["uuid"])
    pivots = {"body": [8, 0, 8], "lid": list(S.HINGE), "face_plate": [8, 6.5, -3], "candy_fill": [8, 3, 8],
              "reveal_a": [8, 8, 8], "reveal_b": [8, 8, 8], "reveal_c": [8, 8, 8]}
    outliner = []
    for p in S.PIECES:
        sub = [{"name": g, "origin": pivots[p], "color": 0, "uuid": _u(f"grp:{p}:{g}"), "export": True, "isOpen": False, "locked": False,
                "visibility": True, "autouv": 0, "children": kids} for g, kids in groups.get(p, {}).items()]
        outliner.append({"name": p, "origin": pivots[p], "color": 0, "uuid": _u("piece:" + p), "export": True, "isOpen": p != "candy_fill",
                         "locked": False, "visibility": True, "autouv": 0, "children": sub})
    tex = {"path": "vault.png", "name": "vault.png", "folder": "", "namespace": "cobbletowers", "id": "0", "particle": True, "render_mode": "default",
           "render_sides": "auto", "frame_time": 1, "frame_order_type": "loop", "frame_order": "", "frame_interpolate": False, "visible": True,
           "internal": True, "saved": True, "uuid": _u("texture"), "source": "data:image/png;base64," + base64.b64encode(atlas_png_bytes).decode()}
    outliner = [{"name": "vault_root", "origin": [8, 0, 8], "color": 0, "uuid": _u("root"), "export": True, "isOpen": True, "locked": False,
                 "visibility": True, "autouv": 0, "children": outliner}]
    return {
        "meta": {"format_version": "4.10", "model_format": "java_block", "box_uv": False},
        "name": "jack_o_lantern_vault",
        "model_identifier": "",
        "visible_box": [1, 1, 0],
        "variable_placeholders": "",
        "variable_placeholder_buttons": [],
        "timeline_setups": [],
        "unhandled_root_fields": {},
        "resolution": {"width": size, "height": size},
        "elements": elements,
        "outliner": outliner,
        "textures": [tex],
        "animations": animations,
    }
